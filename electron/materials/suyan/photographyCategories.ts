export type LabelLayer = "category" | "tag" | "unknown";

/**
 * Which layer a label belongs to. Both admission gates route through this so the
 * boundary can never drift between them.
 *
 * - "category": 命中分类本体（叶子或别名）
 * - "tag": 命中标签层词表（景别/机位/构图/光影/材质）
 * - "unknown": 自由词，由各自的准入规则进一步判断
 */
export function resolveLabelLayer(value: string): LabelLayer {
  const label = value.trim();
  if (!label) {
    return "unknown";
  }
  // 标签层词表优先：这些词绝不允许被别名表拉进分类。
  if (isTagLayerVocabulary(label)) {
    return "tag";
  }
  return resolvePhotographyCategory(label) ? "category" : "unknown";
}

