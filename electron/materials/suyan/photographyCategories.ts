export type TagAdmissionDecision = {
  admitted: boolean;
  reason: string;
  layer?: string;
};

/**
 * Tags are flexible, but still gated:
 * - never admit ontology Genre names
 * - never admit pseudo-genre compounds
 * - prefer short concrete feature words
 */
export function evaluateTagAdmission(value: string): TagAdmissionDecision {
  const label = value.trim();
  if (!label || label === "未分类") {
    return { admitted: false, reason: "空标签" };
  }
  if (isWatermarkLabel(label)) {
    return { admitted: false, reason: "水印/版权/来源叠加元数据，不作标签" };
  }
  if (isFramingCompositionCameraLabel(label)) {
    return { admitted: false, reason: "景别/构图/机位，画面执行细节，不作标签" };
  }
  if (isCategoryOnlyTagLabel(label)) {
    return { admitted: false, reason: "分类维度或来源元数据，不能写入标签" };
  }
  const layer = resolveLabelLayer(label);
  // 景别/机位/构图/光影/材质：标签层专属词，直接放行，不再走伪分类等分类侧规则。
  if (layer === "tag") {
    return { admitted: true, reason: "标签层词表（画面事实）", layer: "feature" };
  }
  if (layer === "category" || photographyCategoryLabels.includes(label)) {
    return { admitted: false, reason: "这是分类，不能写入标签" };
  }
  if (isPseudoPhotographyGenreLabel(label)) {
    return { admitted: false, reason: "伪分类短语，应拆成特征词（如 红色 + 产品主体）" };
  }
  if (label.length > 16) {
    return { admitted: false, reason: "过长，不像短特征标签" };
  }
  if (/^(请|不要|必须|生成|提示词|参数|变量)/.test(label)) {
    return { admitted: false, reason: "指令/参数语句，不是特征标签" };
  }
  return { admitted: true, reason: "通过 Tag 准入", layer: "feature" };
}

function normalizePhotographyCategoryKey(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/\s+/g, "")
    .replace(/[·•]/g, "")
    .replace(/[／/]/g, "/");
}
