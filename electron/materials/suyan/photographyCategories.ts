// Aliases first, canonical labels second: a leaf name must always resolve to itself.
// 维度叶子（如「长曝光」「浅景深」）与旧别名（长曝光 → 长曝光摄影）同名，
// 反过来排列会让叶子被别名劫持，分类识别就再也选不中该维度。
const normalizedCategoryMap = new Map<string, string>(
  [
    ...photographyCategoryAliases.map(([alias, category]): [string, string] => [
      normalizePhotographyCategoryKey(alias),
      category,
    ]),
    ...photographyCategoryLabels.map((category): [string, string] => [
      normalizePhotographyCategoryKey(category),
      category,
    ]),
  ],
);

export function resolvePhotographyCategory(value: string): string | null {
  const normalizedValue = normalizePhotographyCategoryKey(value);

  if (!normalizedValue) {
    return null;
  }

  return normalizedCategoryMap.get(normalizedValue) ?? null;
}

export function normalizePhotographyCategorySuggestions(values: readonly string[]): string[] {
  const suggestions: string[] = [];

  for (const value of values) {
    const category = resolvePhotographyCategory(value);

    if (!category || suggestions.includes(category)) {
      continue;
    }

    suggestions.push(category);
  }

  return suggestions;
}

/**
 * AI 分类展示只保留“画面是什么/属于什么场景”的稳定维度。
 * 光线、色彩、景深/后期技法和情绪是视觉属性，不进入素材详情的分类胶囊，
 * 否则模型很容易把「柔光」「棚拍光」「红色主导」「浪漫唯美」「浅景深」
 * 当成与题材同等重要的分类，产生用户无法检索的噪声。
 */
export const hiddenAiCategoryGroups = ["光线条件", "色彩体系", "技术手法", "情绪氛围"] as const;

const hiddenAiCategoryLabels = new Set(
  photographyCategoryDefinitions
    .filter((definition) => hiddenAiCategoryGroups.includes(definition.group as (typeof hiddenAiCategoryGroups)[number]))
    .map((definition) => definition.label),
);

export function isHiddenAiCategoryLabel(value: string): boolean {
  const category = resolvePhotographyCategory(value);
  return Boolean(category && hiddenAiCategoryLabels.has(category));
}

/** Normalize only the AI/category-analysis path; manual taxonomy editing remains unrestricted. */
export function normalizeAiCategorySuggestions(values: readonly string[]): string[] {
  return normalizePhotographyCategorySuggestions(values).filter((category) => !hiddenAiCategoryLabels.has(category));
}

